const feedContainer = document.getElementById('feedContainer');
const emptyState = document.getElementById('emptyState');
const entryCountSpan = document.getElementById('entryCount');

function renderEntries(entries) {
  feedContainer.querySelectorAll('.entry-card').forEach(el => el.remove());

  if (!Array.isArray(entries) || entries.length === 0) {
    updateEntryCount(0);
    return;
  }

  entries
    .slice()
    .sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt))
    .forEach(entry => feedContainer.appendChild(buildCard(entry)));

  updateEntryCount(entries.length);
}

function buildCard(entry) {
  const card = document.createElement('div');
  card.className = 'entry-card';

  const header = document.createElement('div');
  header.className = 'card-header';

  const subjectSpan = document.createElement('span');
  subjectSpan.className = 'subject-title';
  subjectSpan.textContent = entry.subject || '(no subject)';

  const timeSpan = document.createElement('span');
  timeSpan.className = 'timestamp';
  if (entry.createdAt) {
    const d = new Date(entry.createdAt);
    if (!isNaN(d)) {
      timeSpan.textContent =
        d.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' }) +
        ' · ' +
        d.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });
    } else {
      timeSpan.textContent = entry.createdAt;
    }
  }

  header.append(subjectSpan, timeSpan);
  card.appendChild(header);

  const body = document.createElement('div');
  body.className = 'card-body';

  (entry.blocks || []).forEach(block => {
    if (block.type === 'text') {
      const div = document.createElement('div');
      div.className = 'card-text-block';
      div.textContent = block.content || '';
      body.appendChild(div);
    } else if (block.type === 'image') {
      const wrap = document.createElement('div');
      wrap.className = 'card-image-block';
      const img = document.createElement('img');
      img.src = block.path;
      img.alt = entry.subject || 'image';
      img.loading = 'lazy';
      wrap.appendChild(img);
      body.appendChild(wrap);
    }
  });

  card.appendChild(body);
  return card;
}

function updateEntryCount(count) {
  entryCountSpan.textContent = `${count} ${count === 1 ? 'entry' : 'entries'}`;
  emptyState.classList.toggle('hidden', count > 0);
}

window.addEventListener('DOMContentLoaded', () => renderEntries(ENTRIES));
